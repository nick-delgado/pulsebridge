"""The demo session token: a JWT (RFC 7519) signed with HMAC-SHA256 (``HS256``), carried in
the ``__session`` cookie (D16; the cookie itself is set in ``fhir_proxy.app``).

1. **A random key, not a password.** The HMAC key is the mounted ``session-signing-key`` secret
   (``fhir_proxy.signing_key``): at least 32 random bytes, generated by a script and never
   typed by a person. With 256 random bits there is nothing to guess offline from a token, so
   no password key-derivation function (the scrypt step D9 needed) is used.
2. **Rotation ends every session.** A new secret version gives a new key, and every token
   signed under the old one fails its signature check, with nothing to store.
3. **A fixed algorithm.** Verification accepts ``HS256`` only (``algorithms=["HS256"]``), so a
   token whose header says ``none``, ``HS512`` or ``RS256`` is refused before any key is used:
   the "algorithm confusion" attacks on JWT need a verifier that lets the token choose.
4. **Claims.** ``iss`` and ``aud`` (both ``TOKEN_ISSUER``), ``iat``, ``exp`` (``iat`` + the
   lifetime, 24 hours by default) and ``jti`` (random; T46 keys its per-session limits on it).
   No personal data: a demo visitor is anonymous. The expiry is checked against an injected
   clock: valid while ``now < exp``.
"""

from __future__ import annotations

import re
import secrets
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta

import jwt

ALGORITHM = "HS256"
# A session token is about 200 characters. Anything far longer is refused before parsing.
MAX_TOKEN_LENGTH = 2048
# The three base64url parts of a compact JWS (RFC 7515 section 7.1), nothing else.
TOKEN_SHAPE = re.compile(r"[A-Za-z0-9_-]{1,1024}\.[A-Za-z0-9_-]{1,1024}\.[A-Za-z0-9_-]{1,512}")
# What issue() puts in jti (secrets.token_urlsafe(16): 22 base64url characters).
JTI_SHAPE = re.compile(r"[A-Za-z0-9_-]{16,64}", re.ASCII)
# A token issued in the future by more than this (clock skew between instances) is refused.
MAX_FUTURE_SKEW = timedelta(seconds=60)


class InvalidToken(Exception):
    """The token is not valid. ``str()`` is a fixed reason code, never the token."""


@dataclass(frozen=True)
class IssuedToken:
    token: str
    expires_at: datetime


class TokenSigner:
    """Issues and verifies session tokens with the key in force (passed in on each call, so a
    rotated key is used as soon as it is read)."""

    def __init__(
        self,
        *,
        issuer: str,
        ttl_seconds: int,
        clock: Callable[[], datetime] = lambda: datetime.now(UTC),
    ) -> None:
        self._issuer = issuer
        self._ttl = timedelta(seconds=ttl_seconds)
        self._clock = clock

    def issue(self, key: bytes) -> IssuedToken:
        now = self._clock().replace(microsecond=0)
        expires = now + self._ttl
        claims = {
            "iss": self._issuer,
            "aud": self._issuer,
            "iat": int(now.timestamp()),
            "exp": int(expires.timestamp()),
            "jti": secrets.token_urlsafe(16),
        }
        token = jwt.encode(claims, key, algorithm=ALGORITHM)
        return IssuedToken(token=token, expires_at=expires)

    def verify(self, token: str, key: bytes) -> dict:
        """The token's claims, or :class:`InvalidToken` with a reason code."""
        if not isinstance(token, str) or len(token) > MAX_TOKEN_LENGTH:
            raise InvalidToken("malformed")
        if not TOKEN_SHAPE.fullmatch(token):
            raise InvalidToken("malformed")
        try:
            header = jwt.get_unverified_header(token)
        except jwt.PyJWTError:
            raise InvalidToken("malformed") from None
        # Checked before any key is used, and again by PyJWT (algorithms=[...]).
        if header.get("alg") != ALGORITHM:
            raise InvalidToken("wrong-algorithm")
        try:
            claims = jwt.decode(
                token,
                key,
                algorithms=[ALGORITHM],
                audience=self._issuer,
                issuer=self._issuer,
                # Expiry and issue time are checked below against the injected clock.
                options={
                    "require": ["iss", "aud", "iat", "exp", "jti"],
                    "verify_exp": False,
                    "verify_iat": False,
                    "verify_nbf": False,
                },
            )
        except jwt.InvalidSignatureError:
            raise InvalidToken("bad-signature") from None
        except jwt.PyJWTError:
            raise InvalidToken("bad-claims") from None
        exp, iat = claims.get("exp"), claims.get("iat")
        if not all(isinstance(v, int) and not isinstance(v, bool) for v in (exp, iat)):
            raise InvalidToken("bad-claims")
        jti = claims.get("jti")
        if not (isinstance(jti, str) and JTI_SHAPE.fullmatch(jti)):
            # T46 keys its per-session limits on jti, so it must be the kind issue() makes.
            raise InvalidToken("bad-claims")
        now = self._clock().timestamp()
        if now >= exp:
            raise InvalidToken("expired")
        if iat > now + MAX_FUTURE_SKEW.total_seconds() or exp - iat > self._ttl.total_seconds():
            raise InvalidToken("bad-claims")
        return claims
