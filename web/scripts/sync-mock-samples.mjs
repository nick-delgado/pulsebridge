// Copies the malformed HL7v2 samples from T07's manifest into the mock's data, so mock mode
// shows the samples' real bytes and expected outcomes instead of an imitation.
//   node scripts/sync-mock-samples.mjs          (writes src/api/mock-samples.json)
//   node scripts/sync-mock-samples.mjs --check  (exits 1 if the copy is stale)
// Source: libs/pulsebridge_hl7v2/samples/samples.json (synthetic messages, T07).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, '../../libs/pulsebridge_hl7v2/samples/samples.json');
const TARGET = resolve(here, '../src/api/mock-samples.json');

const manifest = JSON.parse(readFileSync(SOURCE, 'utf8'));
const samples = manifest.samples
  .filter((s) => s.class !== 'valid')
  .map((s) => ({
    name: s.name,
    class: s.class,
    description: s.description,
    transports: s.transports,
    // How the sample is framed over MLLP (`standard`, or a deliberate defect such as
    // `missing_end_block`); cuff-sim reports it as `framing` in its send result.
    mllpFraming: s.mllp_framing,
    // The sample's own MSH-10, picked by position from its first segment for the mock's
    // display only (null when the sample has no MSH, or an empty MSH-10). Not an HL7v2 parser:
    // T13 sends the bytes and T31 records whatever control ID the sender knew.
    controlId: s.segments[0]?.startsWith('MSH') ? s.segments[0].split('|')[9] || null : null,
    // The message payload exactly as T07's loader rebuilds it: segments joined by the sample's
    // own terminator (CR, LF or CR LF), with a final one when the sample has it. MLLP framing
    // defects are not part of the payload.
    er7:
      s.segments.join(s.segment_terminator) +
      (s.terminate_last_segment ? s.segment_terminator : ''),
    expected: {
      commit_ack: s.expected.commit_ack,
      commit_ack_reason: s.expected.commit_ack_reason,
      no_ack: s.expected.no_ack,
      application_outcome: s.expected.application_outcome,
      mapping_reason: s.expected.mapping_reason,
    },
  }));

const output =
  JSON.stringify(
    {
      about:
        'Generated by web/scripts/sync-mock-samples.mjs from libs/pulsebridge_hl7v2/samples/samples.json (T07). Synthetic. Do not edit by hand.',
      samples,
    },
    null,
    2,
  ) + '\n';

if (process.argv.includes('--check')) {
  if (readFileSync(TARGET, 'utf8') !== output) {
    console.error('src/api/mock-samples.json is stale: run node scripts/sync-mock-samples.mjs');
    process.exit(1);
  }
  console.log('mock samples are in step with T07');
} else {
  writeFileSync(TARGET, output);
  console.log(`wrote ${samples.length} samples to src/api/mock-samples.json`);
}
