# ---- 4. lock files -------------------------------------------------------------------------


def lock_entries(path: Path) -> dict[str, dict]:
    text = path.read_text()
    out = {}
    for m in re.finditer(r'provider "([^"]+)" \{(.*?)\n\}', text, re.S):
        body = m.group(2)
        out[m.group(1)] = {
            "version": re.search(r'version\s+=\s+"([^"]+)"', body).group(1),
            "constraints": re.search(r'constraints\s+=\s+"([^"]+)"', body).group(1),
            "hashes": sorted(re.findall(r'"((?:h1|zh):[^"]+)"', body)),
        }
    return out


def check_lock_files() -> None:
    bootstrap = lock_entries(REPO / "infra" / "bootstrap" / ".terraform.lock.hcl")
    module_constraints = set()
    for versions in (REPO / "infra" / "modules").glob("*/versions.tf"):
        for _name, constraint in re.findall(
            r'(google(?:-beta)?)\s*=\s*\{[^}]*?version\s*=\s*"([^"]+)"', versions.read_text(), re.S
        ):
            module_constraints.add(constraint)
    if module_constraints != {"~> 8.11"}:
        fail(
            f"the modules' provider constraints changed: {module_constraints}; "
            "update the roots and their lock files"
        )
    for root in ROOTS:
        path = ENVS / root / ".terraform.lock.hcl"
        if not path.is_file():
            fail(f"{root}/.terraform.lock.hcl is missing (root modules commit their lock file)")
            continue
        entries = lock_entries(path)
        for provider in (
            "registry.terraform.io/hashicorp/google",
            "registry.terraform.io/hashicorp/google-beta",
        ):
            e = entries.get(provider)
            if e is None:
                fail(f"{root} lock file lacks {provider}")
                continue
            major, minor = (int(x) for x in e["version"].split(".")[:2])
            if e["constraints"] != "~> 8.11" or major != 8 or minor < 11:
                fail(
                    f"{root} lock: {provider} {e['version']} ({e['constraints']}) "
                    "does not satisfy the modules' ~> 8.11"
                )
            if (
                bootstrap.get(provider, {}).get("version") == e["version"]
                and bootstrap[provider]["hashes"] != e["hashes"]
            ):
                fail(
                    f"{root} lock: {provider} hashes differ from bootstrap's (different platforms?)"
                )
    if (ENVS / "dev" / ".terraform.lock.hcl").read_bytes() != (
        ENVS / "prod" / ".terraform.lock.hcl"
    ).read_bytes():
        fail("dev and prod lock files must be identical")


# ---- 5. providers ---------------------------------------------------------------------------


def check_providers() -> None:
    text = re.sub(r"#.*", "", (ENVS / "dev" / "providers.tf").read_text())
    blocks = dict(re.findall(r'provider\s+"([\w-]+)"\s*\{(.*?)\n\}', text, re.S))
    if set(blocks) != {"google", "google-beta"}:
        fail(f"providers.tf must configure exactly google and google-beta, found {sorted(blocks)}")
    for name, body in blocks.items():
        if not re.search(r"^\s*project\s*=\s*var\.project_id\s*$", body, re.M):
            fail(f"provider {name} must set project = var.project_id")
        if "alias" in body:
            fail(f"provider {name}: no aliases (the modules use the default configurations)")
    beta = blocks.get("google-beta", "")
    if not re.search(r"^\s*user_project_override\s*=\s*true\s*$", beta, re.M) or not re.search(
        r"^\s*billing_project\s*=\s*var\.project_id\s*$", beta, re.M
    ):
        fail(
            "provider google-beta needs user_project_override = true and "
            "billing_project = var.project_id"
        )


# ---- 6. ordering, version constraints and sensitivity ------------------------------------------


def module_block(text: str, name: str) -> str:
    m = re.search(r'^module\s+"' + name + r'"\s*\{', text, re.M)
    if not m:
        return ""
    depth, i = 1, m.end()
    while i < len(text) and depth:
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
    return text[m.end() : i - 1]


# module -> modules it must depend_on (explicitly): the APIs (project-base) and the secret
# accessor grants (identity) must exist first (module READMEs, "For T25").
REQUIRED_DEPENDS_ON = {
    "ingestion": {"identity", "project_base"},
    "phr": {"project_base", "identity"},
}

# T38: modules whose call must have NO module-level depends_on. A module-level depends_on makes
# every data source inside the module wait for every pending change in the modules it names, so
# the data source is read only at apply. identity's data source gives the project number that
# module healthcare's agent grants are built from, and healthcare took a module-level depends_on on
# project-base before T38: enabling one API then made the grants' members unknown and replaced
# them. healthcare orders itself after the APIs through its enabled_apis input instead.
FORBIDDEN_DEPENDS_ON = ("identity", "healthcare")


def check_ordering_and_versions() -> None:
    stack = re.sub(r"#.*", "", (ENVS / "_stack" / "main.tf").read_text())
    for module, needed in REQUIRED_DEPENDS_ON.items():
        body = module_block(stack, module)
        m = re.search(r"depends_on\s*=\s*\[([^\]]*)\]", body)
        got = set(re.findall(r"module\.(\w+)", m.group(1))) if m else set()
        if not body or not needed <= got:
            fail(
                f"_stack/main.tf: module {module} must depend_on {sorted(needed)}, "
                f"found {sorted(got)}"
            )
    for module in FORBIDDEN_DEPENDS_ON:
        body = module_block(stack, module)
        if not body:
            fail(f"_stack/main.tf: no module {module} block")
        elif re.search(r"^\s*depends_on\s*=", body, re.M):
            fail(
                f"_stack/main.tf: module {module} must have no module-level depends_on "
                "(it defers data sources and replaced healthcare's agent grants; T38)"
            )
    for root in ROOTS:
        text = re.sub(r"#.*", "", (ENVS / root / "versions.tf").read_text())
        if not re.search(r'required_version\s*=\s*">= 1\.11"', text):
            fail(f'{root}/versions.tf must require Terraform ">= 1.11"')
        for name in ("google", "google-beta"):
            m = re.search(name + r"\s*=\s*\{([^}]*)\}", text)
            body = m.group(1) if m else ""
            if f'source  = "hashicorp/{name}"' not in body or 'version = "~> 8.11"' not in body:
                fail(
                    f'{root}/versions.tf must pin {name} to hashicorp/{name} "~> 8.11" '
                    "(the modules' constraint)"
                )
    # The patient's identifier and names, and the alert address, are personal data: sensitive at
    # the root and in the stack, so plans (posted on pull requests by T26) show "(sensitive value)"
    # (plan_scan.py proves it).
    for path in (ENVS / "dev" / "variables.tf", ENVS / "_stack" / "variables.tf"):
        text = path.read_text()
        for name in ("patient_id", "patient_family_name", "patient_given_name", "alert_email"):
            m = re.search(r'^variable\s+"' + name + r'"\s*\{(.*?)^\}', text, re.S | re.M)
            if not m or not re.search(r"^\s*sensitive\s*=\s*true\s*$", m.group(1), re.M):
                fail(f"{path.relative_to(REPO)}: variable {name} must be sensitive = true")


def check_deploy_tools_lockfile() -> None:
    """The page deploy installs the Firebase CLI with `npm ci --ignore-scripts` from this lockfile,
    so every package of its tree must be pinned: resolved from the public npm registry and carrying
    a sha512 integrity hash, and the root dependency must equal package.json's exact version."""
    import json

    manifest = json.loads((DEPLOY_TOOLS / "package.json").read_text())
    lock = json.loads((DEPLOY_TOOLS / "package-lock.json").read_text())
    wanted = manifest.get("dependencies", {})
    if not wanted or not all(re.fullmatch(r"\d+\.\d+\.\d+", v) for v in wanted.values()):
        fail("ci/deploy-tools/package.json must pin exact versions")
    if lock.get("lockfileVersion") != 3 or lock["packages"][""].get("dependencies") != wanted:
        fail(
            "ci/deploy-tools/package-lock.json is not the lockfile of package.json "
            "(regenerate it with npm install --package-lock-only)"
        )
    packages = {k: v for k, v in lock["packages"].items() if k}
    if len(packages) < 10:
        fail("ci/deploy-tools/package-lock.json lists too few packages to be the CLI's tree")
    for name, pkg in packages.items():
        if not pkg.get("resolved", "").startswith("https://registry.npmjs.org/"):
            fail(
                f"ci/deploy-tools/package-lock.json: {name} is not resolved from registry.npmjs.org"
            )
        if not pkg.get("integrity", "").startswith("sha512-"):
            fail(f"ci/deploy-tools/package-lock.json: {name} has no sha512 integrity hash")
    for name, version in wanted.items():
        if packages.get(f"node_modules/{name}", {}).get("version") != version:
            fail(f"ci/deploy-tools/package-lock.json does not lock {name} at {version}")


