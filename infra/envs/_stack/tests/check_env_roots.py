def fail(message: str) -> None:
    failures.append(message)


def git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(REPO), *args], capture_output=True, text=True, check=False
    )


def candidate_files() -> list[Path]:
    """Files under infra/envs that git would commit: tracked, or untracked and not ignored."""
    result = git("ls-files", "-co", "--exclude-standard", "--", "infra/envs")
    if result.returncode != 0:
        raise SystemExit(f"FAIL: git ls-files failed: {result.stderr.strip()}")
    files = [REPO / line for line in result.stdout.splitlines() if line and (REPO / line).is_file()]
    # An empty or partial list would make every scan below pass vacuously.
    missing = [str(f.relative_to(REPO)) for f in KNOWN_FILES if f not in files]
    if not files or missing:
        raise SystemExit(
            f"FAIL: git lists {len(files)} file(s) under infra/envs; missing {missing}"
        )
    return files


def root_files(root: str) -> dict[str, Path]:
    base = ENVS / root
    return {str(p.relative_to(base)): p for p in candidate_files() if base in p.parents}


# ---- 1. dev and prod differ only where documented ---------------------------------------------


def env_settings(text: str) -> dict[str, str]:
    settings = {}
    locals_block = re.search(r"^locals\s*\{(.*?)^\}", text, re.S | re.M)
    body = re.sub(r"#.*", "", locals_block.group(1)) if locals_block else ""
    for key, value in re.findall(r"^\s*(\w+)\s*=\s*(\S+)\s*$", body, re.M):
        settings[key] = value.strip('"')
    variables = re.findall(r'^variable\s+"(\w+)"', text, re.M)
    if variables != ["use_synthetic_data"]:
        fail(f"env.tf may declare only the use_synthetic_data variable, found {variables}")
    default = re.search(
        r'^variable\s+"use_synthetic_data"\s*\{.*?^\s*default\s*=\s*(\w+)', text, re.S | re.M
    )
    settings["use_synthetic_data_default"] = default.group(1) if default else "?"
    return settings


def check_roots_differ_only_where_documented() -> None:
    files = {root: root_files(root) for root in ROOTS}
    if set(files["dev"]) != set(files["prod"]):
        fail(
            "dev and prod must have the same files; only in one: "
            f"{sorted(set(files['dev']) ^ set(files['prod']))}"
        )
    for name in sorted(set(files["dev"]) & set(files["prod"])):
        same = files["dev"][name].read_bytes() == files["prod"][name].read_bytes()
        if name not in MAY_DIFFER and not same:
            fail(f"{name} differs between dev and prod; only {sorted(MAY_DIFFER)} may")
    for root in ROOTS:
        got = env_settings((ENVS / root / "env.tf").read_text())
        if got != EXPECTED_ENV[root]:
            fail(f"{root}/env.tf settings {got} != documented {EXPECTED_ENV[root]}")
    backends = {root: (ENVS / root / "backend.tf").read_text() for root in ROOTS}
    neutral = {root: re.sub(r"\b(dev|prod)\b", "<env>", text) for root, text in backends.items()}
    if neutral["dev"] != neutral["prod"]:
        fail("dev/backend.tf and prod/backend.tf may differ only in the environment name")
    for root, text in backends.items():
        if not re.search(r'backend\s+"gcs"\s*\{\s*prefix\s*=\s*"' + root + r'"\s*\}', text):
            fail(
                f"{root}/backend.tf must be a partial gcs backend with only "
                f'prefix = "{root}" (no bucket)'
            )
    readme = (ENVS / "README.md").read_text()
    for setting in (
        "protect_from_destroy",
        "use_synthetic_data",
    ):
        if setting not in readme:
            fail(f"infra/envs/README.md must document the dev/prod setting {setting}")


# ---- 2. nothing author-specific --------------------------------------------------------------

EMAIL = re.compile(r"[A-Za-z0-9._%+${}<>-]+@[A-Za-z0-9.${}<>-]+\.[a-z]{2,}")
# A host after "//" (a URL) must be checked too, so "/" is not in the lookbehind (T26 review).
HOST = re.compile(r"(?<![\w.@-])(?:[a-z0-9][a-z0-9-]*\.)+(?:com|org|net|io|app|dev|cloud|me|ai)\b")
PROJECT_PATH = re.compile(r"projects/([a-z][a-z0-9-]{4,28}[a-z0-9])\b")
# A 12-digit number at the end of a sentence ("...123456789012.") is still a number; only a decimal
# fraction (".5") continues it (T26 review).
NUMBER = re.compile(r"(?<![\w.:-])\d{12}(?![\w-]|\.\d)")


def email_is_placeholder(addr: str) -> bool:
    """An address may appear under infra/envs only if it names nobody real: a template
    (`<...>`, `${...}`), example.com/org, a service account in an allowed placeholder project, or
    a Google-managed service agent of an allowed synthetic project number."""
    domain = addr.split("@", 1)[1]
    if any(c in addr for c in "<${") or domain in ("example.com", "example.org"):
        return True
    if domain.endswith(".iam.gserviceaccount.com") and domain.split(".")[0] in ALLOWED_PROJECTS:
        return True
    # A service agent (service-<project number>@gcp-sa-<service>...) names its project by number,
    # so only an allowed number makes it a placeholder (T36). NUMBER does not catch the number
    # here (it is glued to "service-"), so this is the only check on it.
    agent = re.fullmatch(r"service-(\d{12})@gcp-sa-[a-z0-9-]+\.iam\.gserviceaccount\.com", addr)
    return bool(agent) and agent.group(1) in ALLOWED_NUMBERS


def check_patterns() -> None:
    """Positive controls: the patterns must find what they are for, or the scan below passes
    vacuously. A host inside a URL (after "//"), a 12-digit number at the end of a sentence."""
    # Assembled at run time, so this file's own text holds no such host or number.
    host_a = "pulsebridge-demo.example" + ".net"
    host_b = "dashboard.pulsebridge" + ".app"
    number = "1234567890" + "13"
    canaries = {
        "a host in a URL": (HOST, f"see https://{host_a}/x", host_a),
        "a bare host": (HOST, f"at {host_b} today", host_b),
        "a number before a full stop": (NUMBER, f"project number {number}.", number),
        "a number in a path": (NUMBER, f"projects/{number}/secrets/x", number),
    }
    for what, (pattern, text, expected) in canaries.items():
        found = [m.group(0) for m in pattern.finditer(text)]
        if found != [expected]:
            fail(f"pattern self-check: {what} not found as {expected!r} (got {found})")
    # And no false positive on a decimal or a longer number.
    if NUMBER.findall(f"{number}4 and {number}.5"):
        fail("pattern self-check: NUMBER matches a 13-digit number or a decimal")
    # Service agents (T36): one of a synthetic project passes, one of any other number does not.
    agent_domain = "@gcp-sa-pubsub" + ".iam.gserviceaccount.com"
    if not email_is_placeholder("service-100000000001" + agent_domain):
        fail("pattern self-check: a synthetic project's service agent is refused")
    if email_is_placeholder(f"service-{number}" + agent_domain):
        fail("pattern self-check: a service agent of a non-placeholder project number is accepted")


def check_no_hardcoded_identity() -> None:
    for path in candidate_files():
        if path.suffix in (".png", ".jpg") or path in GENERATED_THIRD_PARTY:
            continue
        rel = path.relative_to(REPO)
        text = path.read_text(errors="replace")
        for m in EMAIL.finditer(text):
            addr = m.group(0)
            if not email_is_placeholder(addr):
                fail(f"{rel}: email address {addr!r} is not a placeholder")
        for m in HOST.finditer(text):
            host = m.group(0)
            if not any(host == s or host.endswith("." + s) for s in ALLOWED_DOMAIN_SUFFIXES):
                fail(f"{rel}: host {host!r} is not a placeholder or a Google/tool host")
        for m in PROJECT_PATH.finditer(text):
            if m.group(1) not in ALLOWED_PROJECTS:
                fail(f"{rel}: project {m.group(1)!r} in a resource path is not a placeholder")
        for m in NUMBER.finditer(text):
            if m.group(0) not in ALLOWED_NUMBERS:
                fail(f"{rel}: 12-digit number {m.group(0)} looks like a project number")
        for m in re.finditer(r'\bbucket\s*=\s*"([^"]*)"', text):
            if m.group(1) != "your-project-id-tfstate":
                fail(f"{rel}: bucket {m.group(1)!r} is not the placeholder")
        # A project ID assigned to any project-ish key or local (project, project_id,
        # healthcare_project_id, PROJECT, ...) must be a placeholder.
        for m in re.finditer(
            r'(?im)^\s*\w*project\w*\s*=\s*"([a-z][a-z0-9-]{4,28}[a-z0-9])"', text
        ):
            if m.group(1) not in ALLOWED_PROJECTS:
                fail(f"{rel}: project ID {m.group(1)!r} assigned in code is not a placeholder")
        if path.suffix in (".tf", ".hcl"):
            # Secret values never pass through Terraform here: no data source that reads a secret
            # version, and no secret_data argument (no secret value passes through Terraform, D16).
            code = re.sub(r"#.*", "", text)
            if re.search(r'data\s+"google_secret_manager_secret_version', code) or re.search(
                r"\bsecret_data\b", code
            ):
                fail(f"{rel}: secret versions or secret_data must not appear under infra/envs")
        if path.suffix == ".tf":
            code = re.sub(r"#.*", "", text)
            for word in ("allUsers", "allAuthenticatedUsers", "google_service_account_key"):
                if word in code:
                    fail(f"{rel}: {word!r} must not appear in Terraform code under infra/envs")
            # A provider `credentials = ...` argument would point at a key file.
            if re.search(r"^\s*(credentials|access_token)\s*=", code, re.M):
                fail(f"{rel}: a credentials or access_token argument must not be configured")


# ---- 3. git-ignore rules and the examples ----------------------------------------------------


def check_ignored() -> None:
    must_ignore = [
        f"infra/envs/{r}/{n}"
        for r in ROOTS
        for n in ("terraform.tfvars", "backend.hcl", "terraform.tfstate", "plan.tfplan")
    ]
    must_ignore.append("infra/envs/_stack/.terraform.lock.hcl")
    must_keep = [
        f"infra/envs/{r}/{n}"
        for r in ROOTS
        for n in ("terraform.tfvars.example", "backend.hcl.example", ".terraform.lock.hcl")
    ]
    for path in must_ignore:
        if git("check-ignore", "-q", "--no-index", path).returncode != 0:
            fail(f"{path} must be git-ignored")
    for path in must_keep:
        if git("check-ignore", "-q", "--no-index", path).returncode == 0:
            fail(f"{path} must NOT be git-ignored (it is committed)")
        if not (REPO / path).is_file():
            fail(f"{path} is missing")


def declared_variables(root: str) -> dict[str, bool]:
    """variable name -> has a default, from the root's .tf files."""
    out = {}
    for tf in (ENVS / root).glob("*.tf"):
        for m in re.finditer(r'^variable\s+"(\w+)"\s*\{(.*?)^\}', tf.read_text(), re.S | re.M):
            out[m.group(1)] = bool(re.search(r"^\s*default\s*=", m.group(2), re.M))
    return out


def check_example(root: str) -> None:
    path = ENVS / root / "terraform.tfvars.example"
    declared = declared_variables(root)
    assigned = {}
    for line in path.read_text().splitlines():
        m = re.match(r"^(\w+)\s*=\s*(.+?)\s*(?:#.*)?$", line)
        if m:
            assigned[m.group(1)] = m.group(2)
    for name, value in assigned.items():
        if name not in declared:
            fail(
                f"{root}/terraform.tfvars.example sets {name}, which is not a variable of the root"
            )
        for s in re.findall(r'"([^"]*)"', value):
            if s not in PLACEHOLDER_STRINGS:
                fail(f"{root}/terraform.tfvars.example: {name} = {s!r} is not a known placeholder")
    required = {n for n, has_default in declared.items() if not has_default}
    missing = required - set(assigned)
    if missing:
        fail(f"{root}/terraform.tfvars.example lacks the required variable(s) {sorted(missing)}")


def tf_env() -> tuple[dict[str, str], str]:
    env = {k: v for k, v in os.environ.items() if k not in CREDENTIAL_VARS}
    home = tempfile.mkdtemp(prefix="env-roots-check-home-")
    env.update(
        HOME=home,
        CLOUDSDK_CONFIG=os.path.join(home, "gcloud"),
        GCE_METADATA_HOST="127.0.0.1:9",
        GCE_METADATA_IP="127.0.0.1:9",
        NO_GCE_CHECK="True",
        CHECKPOINT_DISABLE="1",
        TF_IN_AUTOMATION="1",
    )
    return env, home


